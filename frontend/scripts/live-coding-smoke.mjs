// Only the isolated pytest browser integration supplies these fixture values.
import { chromium,expect } from '@playwright/test';
const backend=process.env.TTH_BACKEND_URL;
const round=process.env.TTH_CODING_ROUND;
if (!backend || !round) throw new Error('Run through the isolated coding browser integration.');
const origin='http://127.0.0.1:5173';
const browser=await chromium.launch();
const contexts=[];
try {
  async function context() {
    const ctx=await browser.newContext();
    contexts.push(ctx);
    for (const path of ['api','admin']) await ctx.route(`${origin}/${path}/**`,async route=>{
      const url=new URL(route.request().url());
      await route.fulfill({ response:await route.fetch({ url:`${backend}${url.pathname}${url.search}`,maxRedirects:0 }) });
    });
    return ctx;
  }
  const staff=await context();
  const desk=await staff.newPage();
  await desk.goto(`${origin}/staff/rounds`);
  await desk.getByRole('link',{ name:'Staff sign in',exact:true }).click();
  await desk.locator('#id_username').fill('coding-maker');
  await desk.locator('#id_password').fill('test-only');
  await desk.getByRole('button',{ name:'Log in',exact:true }).click();
  const team=await context();
  const page=await team.newPage();
  await page.goto(`${origin}/login`);
  await page.getByLabel('Team code').fill('CODE-0');
  await page.getByLabel('Password').fill('test-only');
  await page.getByRole('button',{ name:'Sign in',exact:true }).click();
  await expect(page).toHaveURL(`${origin}/lobby`);
  await page.goto(`${origin}/rounds/${round}/coding`);
  await expect(page.getByText('Ask the supervisor to assign this browser before the task set opens.')).toBeVisible();
  const state=await page.request.get(`${backend}/api/rounds/${round}/coding/submission`);
  const session=(await state.json()).session_id;
  const lab=await staff.newPage();
  await lab.goto(`${origin}/staff/coding?round=${round}`);
  await lab.getByLabel('Team browser session').selectOption(String(session));
  await lab.getByLabel('Workstation label').fill('SYNTHETIC-LAB-1');
  await lab.getByLabel('Assignment reason').fill('Verified synthetic workstation');
  await lab.getByLabel('Supervisor station evidence').fill('synthetic-station-sheet');
  await lab.getByRole('button',{ name:'Assign workstation' }).click();
  await expect(lab.getByText('Coding action confirmed.')).toBeVisible();
  await desk.getByLabel('Reason',{ exact:true }).fill('Open synthetic coding lobby');
  await desk.getByRole('button',{ name:'Apply: Open lobby',exact:true }).click();
  await expect(desk.getByText('Waiting for the start',{ exact:true })).toBeVisible();
  await desk.getByLabel('Reason',{ exact:true }).fill('Start synthetic coding');
  await desk.getByRole('button',{ name:'Apply: Start round',exact:true }).click();
  await expect(desk.getByText('Round live',{ exact:true })).toBeVisible();
  await page.reload();
  await page.getByLabel('Response for OUTPUT',{ exact:true }).fill('private correct answer');
  await expect(page.getByText('Saved response version 1.')).toBeVisible();
  await page.getByRole('checkbox',{ name:'I checked my saved responses and am ready to lock this work.' }).check();
  await page.getByRole('button',{ name:'Final submit and lock work' }).click();
  await expect(page.getByRole('heading',{ name:'Final submission recorded' })).toBeVisible();
  await desk.getByLabel('Round action').selectOption('end');
  await desk.getByLabel('Reason',{ exact:true }).fill('End synthetic coding for lab review');
  await desk.getByRole('button',{ name:'Apply: End round',exact:true }).click();
  await expect(desk.getByText('Round ended',{ exact:true })).toBeVisible();
  await lab.getByRole('button',{ name:'Refresh coding desk' }).click();
  await lab.getByText('CODE-0 · manual · awaiting judgment marks').click();
  await lab.getByRole('checkbox',{ name:'Fully correct: OUTPUT' }).check();
  await lab.getByLabel('Private judging reason').fill('Compared the frozen output response with its rubric');
  await lab.getByLabel('Lab execution evidence references').fill('synthetic-lab-rubric-check');
  await lab.getByLabel('Supervisor final-time evidence').fill('synthetic-supervisor-time-check');
  const gradeResponse=lab.waitForResponse(response=>response.url().endsWith('/coding/judgment') && response.request().method()==='POST');
  await lab.getByRole('button',{ name:'Propose lab judgment' }).click();
  const grade=(await (await gradeResponse).json()).judgment_proposal_id;
  await expect(lab.getByText(`Judgment ${grade} · CODE-0 · awaiting review`)).toBeVisible();
  const verifier=await context();
  const review=await verifier.newPage();
  await review.goto(`${origin}/staff/coding?round=${round}`);
  await review.getByRole('link',{ name:'Staff sign in',exact:true }).click();
  await review.locator('#id_username').fill('coding-reviewer');
  await review.locator('#id_password').fill('test-only');
  await review.getByRole('button',{ name:'Log in',exact:true }).click();
  await review.getByText(`Judgment ${grade} · CODE-0 · awaiting review`).click();
  await review.getByLabel('Lab review reason').fill('Independent source and supervisor evidence checked');
  await review.getByRole('checkbox',{ name:'I independently checked source versions, lab tests, marks and supervisor time.' }).check();
  await review.getByRole('button',{ name:`Approve lab judgment ${grade}` }).click();
  await expect(review.getByText('Coding action confirmed.')).toBeVisible();
  await lab.goto(`${origin}/staff/results?round=${round}`);
  await lab.getByLabel('Public publication summary',{ exact:true }).fill('Synthetic coding results independently checked');
  const publicationResponse=lab.waitForResponse(response=>response.url().endsWith('/publish') && response.request().method()==='POST');
  await lab.getByRole('button',{ name:'Submit result proposal' }).click();
  const publication=(await (await publicationResponse).json()).proposal_id;
  await expect(lab.getByText(`Proposal ${publication} · provisional`)).toBeVisible();
  await review.goto(`${origin}/staff/results?round=${round}`);
  await review.getByLabel('Public review summary',{ exact:true }).fill('Independent coding publication review');
  await review.getByRole('checkbox',{ name:'I independently checked the standings, roster, cut and supporting evidence.' }).check();
  const approvedResponse=review.waitForResponse(response=>response.url().endsWith('/publish') && response.request().method()==='POST');
  await review.getByRole('button',{ name:`Approve and publish proposal ${publication}` }).click();
  const approved=await approvedResponse;
  expect(approved.ok()).toBeTruthy();
  expect((await approved.json()).status).toBe('PROVISIONAL');
  await page.goto(`${origin}/rounds/${round}/results`);
  await expect(page.getByRole('heading',{ name:'Provisional results · revision 1' })).toBeVisible();
  await expect(page.getByRole('columnheader',{ name:'Fully correct tasks' })).toBeVisible();
  console.log('Real HTTP coding assignment, save, final lock, lab judgment and two-person publication passed.');
} finally {
  for (const ctx of contexts) await ctx.unrouteAll({ behavior:'wait' });
  await browser.close();
}
